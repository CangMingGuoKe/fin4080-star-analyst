BODY_SCALE = 1.35


def add_rect(slide, x, y, w, h, fill=LIGHT, line=None, shape=MSO_SHAPE.RECTANGLE):
    shp = slide.shapes.add_shape(shape, Inches(x), Inches(y), Inches(w), Inches(h))
    shp.fill.solid()
    shp.fill.fore_color.rgb = fill
    if line is None:
        shp.line.fill.background()
    else:
        shp.line.color.rgb = line
        shp.line.width = Pt(0.75)
    shp.shadow.inherit = False
    return shp


def add_line(slide, x1, y1, x2, y2, color=NAVY, width=1.25):
    line = slide.shapes.add_connector(
        MSO_CONNECTOR.STRAIGHT, Inches(x1), Inches(y1), Inches(x2), Inches(y2)
    )
    line.line.color.rgb = color
    line.line.width = Pt(width)
    return line


def add_text(slide, x, y, w, h, text, size=14, bold=False, color=NAVY,
             align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP, line_spacing=1.0,
             space_after=0, italic=False, letter_spacing=None,
             scale=BODY_SCALE):
    tb = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.clear()
    tf.word_wrap = True
    tf.auto_size = MSO_AUTO_SIZE.NONE
    tf.margin_left = 0
    tf.margin_right = 0
    tf.margin_top = 0
    tf.margin_bottom = 0
    tf.vertical_anchor = anchor
    p = tf.paragraphs[0]
    p.alignment = align
    p.line_spacing = line_spacing
    p.space_after = Pt(space_after)
    r = p.add_run()
    r.text = text
    r.font.name = FONT
    r.font.size = Pt(size * scale)
    r.font.bold = bold
    r.font.italic = italic
    r.font.color.rgb = color
    if letter_spacing is not None:
        r.font._element.set('spc', str(int(letter_spacing * 100)))
    return tb


def add_rich(slide, x, y, w, h, paras, anchor=MSO_ANCHOR.TOP, scale=BODY_SCALE):
    """Add a text box with a list of paragraph dictionaries.

    Each paragraph: {'runs': [{'text', 'size', 'bold', 'color'}], 'space_after',
    'line_spacing', 'align'}.
    """
    tb = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.clear()
    tf.word_wrap = True
    tf.auto_size = MSO_AUTO_SIZE.NONE
    tf.margin_left = 0
    tf.margin_right = 0
    tf.margin_top = 0
    tf.margin_bottom = 0
    tf.vertical_anchor = anchor
    for i, item in enumerate(paras):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = item.get('align', PP_ALIGN.LEFT)
        p.line_spacing = item.get('line_spacing', 1.0)
        p.space_after = Pt(item.get('space_after', 0))
        p.space_before = Pt(item.get('space_before', 0))
        for rd in item['runs']:
            r = p.add_run()
            r.text = rd['text']
            r.font.name = FONT
            r.font.size = Pt(rd.get('size', item.get('size', 14)) * scale)
            r.font.bold = rd.get('bold', False)
            r.font.italic = rd.get('italic', False)
            r.font.color.rgb = rd.get('color', NAVY)
    return tb


def header(slide, eyebrow, title, page, section, title_size=28, rule_y=1.62,
           title_y=0.62, title_h=0.98):
    add_text(slide, 0.7, 0.32, 11.9, 0.24, eyebrow, size=10.5, bold=True,
             color=GRAY, letter_spacing=1.0)
    add_text(slide, 0.7, title_y, 11.9, title_h, title, size=title_size,
             bold=True, color=NAVY, line_spacing=1.02, scale=TITLE_SCALE)
    add_line(slide, 0.7, rule_y, 12.63, rule_y, color=NAVY, width=1.25)
    add_text(slide, 0.7, 7.10, 6.0, 0.25, section, size=8.5, color=GRAY,
             letter_spacing=0.6)
    add_text(slide, 12.05, 7.10, 0.55, 0.25, str(page), size=9.5, color=GRAY,
             align=PP_ALIGN.RIGHT)


def source(slide, text, y=6.82):
    add_text(slide, 0.7, y, 11.9, 0.25, text, size=8.5, color=GRAY)


def notes(slide, text):
    slide.notes_slide.notes_text_frame.text = text


def card(slide, x, y, w, h, label, big=None, body=None, accent=NAVY,
         big_size=30, body_size=11.5, top_bar=True):
    add_rect(slide, x, y, w, h, fill=LIGHT)
    if top_bar:
        add_rect(slide, x, y, w, 0.055, fill=accent)
    add_text(slide, x + 0.2, y + 0.14, w - 0.35, 0.22, label, size=9.5,
             bold=True, color=GRAY, letter_spacing=0.6)
    if big is not None:
        add_text(slide, x + 0.2, y + 0.40, w - 0.35, 0.55, big, size=big_size,
                 bold=True, color=accent, line_spacing=1.0)
    if body is not None:
        by = y + 0.40 + (0.66 if big is not None else 0.0)
        add_text(slide, x + 0.2, by, w - 0.35, h - (by - y) - 0.1, body,
                 size=body_size, color=NAVY, line_spacing=1.05)


def panel(slide, x, y, w, h, title, body_paras, accent=NAVY):
    add_rect(slide, x, y, w, h, fill=LIGHT)
    add_text(slide, x + 0.25, y + 0.2, w - 0.45, 0.25, title, size=11.5,
             bold=True, color=accent, letter_spacing=0.6)
    add_rich(slide, x + 0.25, y + 0.58, w - 0.45, h - 0.75, body_paras)


