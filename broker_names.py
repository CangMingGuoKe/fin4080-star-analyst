"""券商名称规范化：全项目共用一套机构身份映射。

为什么要单独一个模块：star 匹配（build_star_variable.py）和券商层级
（build_broker_tier.py）都要判断「两家机构是不是同一家」。两边各写一份映射，
迟早会不一致，而一次不一致就让 87 条明星分析师的研报被判成非明星。

两类映射，目标名是同一个空间：
  TABLE_VARIANTS  评级表内部的多种写法（改名、后缀变体）-> 规范名
  LIST_ALIAS      新财富名单的写法 -> 规范名

顺序有讲究：子公司排除（EXCLUDE_SUB，见 build_star_variable.py）必须在规范化
之前做，否则「中银国际证券」这种含「国际」二字的正常券商名会被当成子公司排掉。
"""

TABLE_VARIANTS = {
    '中信建投证券': '中信建投',    # 评级表两种写法并存，记录被拆成 10266 + 4512
    '中国银河证券': '中国银河',
    '中银国际证券': '中银国际',    # 与「中银证券」是同一家（601696）
    '中银证券': '中银国际',
    '太平洋证券': '太平洋',
    '联讯证券': '粤开证券',        # 2020 年改名，旧名仍留在历史记录里
    '财富证券': '财信证券',        # 同上
    '国泰君安证券': '国泰君安',    # 2018 年评级表里还有 7 条这种写法
    '国泰海通证券': '国泰海通',    # 新名的完整写法
    '安信证券': '国投证券',        # 2024 年改名，分析师重合 26/32
    '国联证券': '国联民生',        # 2025 年合并；样本内先归到新名
    '国联民生证券': '国联民生',
    '华菁证券': '华兴证券',        # 2020 年改名，分析师重合 3/4
    '新时代证券': '诚通证券',      # 2022 年更名，样本内记录很少
}

# 新名 -> (旧名, 新名首次生效的年份)。只用于显示：事件表保留原始名称，
# 这个表让报告可以按年份写回当时在用的名字，而不是事后统一成新名。
RENAME_HISTORY = {
    '国泰海通': ('国泰君安', 2025),
    '国投证券': ('安信证券', 2024),
    '国联民生': ('国联证券', 2025),
    '华兴证券': ('华菁证券', 2021),
    '诚通证券': ('新时代证券', 2022),
    '粤开证券': ('联讯证券', 2020),
    '财信证券': ('财富证券', 2020),
}

LIST_ALIAS = {
        # 中金公司：机构评级明细里没有「以它为研究机构」的记录。2020-2024 里出现的 237 处
    # 「中金公司」全部是股票简称（即关于中金公司这只股票的研报），全称列也没出现过它，
    # 所以其分析师无法匹配，标为 None。
    '中金公司': None,
    '银河证券': '中国银河',        # 名单写「银河证券」，评级表写「中国银河」
    '国联民生证券': '国联民生',
    '国泰海通证券': '国泰海通',
    '申万宏源证券': '申万宏源',
}


def _split_name(n):
    """有的记录把两个机构名用分号拼在一起，例如「国泰君安;国泰君安证券」。"""
    for sep in (';', '；'):
        if sep in n:
            n = n.split(sep)[0].strip()
    return n


def canonical_broker(name, year=None):
    """稳定身份：同一家券商的所有历史写法并到一个名字，用于跨年汇总与匹配。

    year 参数保留是为了兼容既有调用；身份本身不随年份变化。需要"当年在用的
    名称"时用 broker_name_in_year。
    """
    n = _split_name(str(name).strip())
    return TABLE_VARIANTS.get(n, n)


def broker_name_in_year(name, year):
    """返回该机构在指定年份正在使用的名称，用于报告与展示。

    例：国泰君安在 2024 年及以前显示国泰君安，2025 年起显示国泰海通；
    安信证券在 2023 年及以前显示安信证券，2024 年起显示国投证券。
    """
    n = canonical_broker(name)
    if year is None:
        return n
    y = int(year)
    for new, (old, first) in RENAME_HISTORY.items():
        if n == new and y < first:
            return old
    return n


def from_list(name, year=None):
    """名单侧：新财富写法 -> 规范名。返回 None 表示该机构在评级表里不存在。"""
    n = _split_name(str(name).strip())
    n = LIST_ALIAS.get(n, n)
    return None if n is None else canonical_broker(n, year)

# 分析师姓名也偶有字符差错（抓榜单页面时极少数名字写错）。
# 实测一处：榜单把海通证券机械行业的佘炜超写成「余炜超」，
# 而评级明细里 641 条记录全是「佘炜超」、0 条「余炜超」，以评级明细为准。
ANALYST_ALIASES = {
    '余炜超': '佘炜超',
}


def canonical_analyst(name):
    """分析师姓名规范化：榜单侧的差错写法并到评级明细的写法。"""
    n = str(name).strip()
    return ANALYST_ALIASES.get(n, n)
