"""Build the FIN4080 Project 10 slide deck as an editable .pptx.

Design follows the sample deck's grammar: one assertion per slide, an
all-caps question eyebrow, a thin rule, large result numbers, and a small
number of text panels. All text and shapes are native PowerPoint objects.
The three result charts are PNGs generated by make_ppt_figures.py.
"""
